def main():
    if not os.path.exists(os.path.join(OUT_DIR, "champion_names.json")):
        print("没有 champion_names.json，请先运行 metadata.py")
        return
    champs = json.load(open(os.path.join(OUT_DIR, "champion_names.json"), encoding="utf-8"))
    name2id = {}
    for cid, c in champs.items():
        name2id.setdefault(c["name"], cid)
    tags = {}
    missing = []
    for name, taglist in NAME_TAGS.items():
        cid = name2id.get(name)
        if cid is None:
            missing.append(name)
            continue
        tags[cid] = list(dict.fromkeys(taglist))
    with open(os.path.join(OUT_DIR, "champion_tags.json"), "w", encoding="utf-8") as f:
        json.dump(tags, f, ensure_ascii=False, indent=2)
    print("已打标签英雄数:", len(tags))
    if missing:
        print("未匹配到ID的名字:", missing)


if __name__ == "__main__":
    main()
